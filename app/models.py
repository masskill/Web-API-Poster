"""Database tables. All datetimes are timezone-aware UTC."""
import json
from datetime import datetime, timezone

from sqlmodel import Field, SQLModel


def utcnow() -> datetime:
    return datetime.now(timezone.utc)


class Account(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    platform: str = Field(index=True)
    name: str
    slug: str
    # Platform-specific keys (Telegram: bot_token, chat_id). Never shown in full.
    config: str = "{}"
    signature: str = ""  # appended to every description of this account
    logged_in_at: datetime | None = None
    created_at: datetime = Field(default_factory=utcnow)

    @property
    def cfg(self) -> dict:
        return json.loads(self.config or "{}")


class Category(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    name: str


class Post(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    video_path: str
    title: str = ""
    description: str = ""
    hashtags: str = ""
    category: str = ""
    scheduled_at: datetime | None = None
    dry_run: bool = True
    group_id: int | None = None
    created_at: datetime = Field(default_factory=utcnow)


class AccountGroup(SQLModel, table=True):
    """A named set of accounts with optional posting slots and an inbox folder."""
    id: int | None = Field(default=None, primary_key=True)
    name: str
    slug: str  # inbox subfolder name
    account_ids: str = "[]"  # JSON list
    slots: str = ""  # local times, e.g. "10:00, 18:00"

    @property
    def ids(self) -> list[int]:
        return json.loads(self.account_ids or "[]")

    @property
    def slot_times(self) -> list[str]:
        return sorted(s.strip() for s in self.slots.replace(";", ",").split(",") if s.strip())


class Job(SQLModel, table=True):
    id: int | None = Field(default=None, primary_key=True)
    post_id: int = Field(foreign_key="post.id", index=True)
    account_id: int = Field(foreign_key="account.id", index=True)
    # pending | running | needs_action | published | dry_run | failed | cancelled
    status: str = Field(default="pending", index=True)
    dry_run: bool = True
    run_at: datetime = Field(default_factory=utcnow)
    text_json: str = "{}"
    result_url: str | None = None
    error_code: str | None = None
    error: str | None = None
    debug_dir: str | None = None
    log: str = ""
    attempts: int = 0
    started_at: datetime | None = None
    finished_at: datetime | None = None


class Setting(SQLModel, table=True):
    key: str = Field(primary_key=True)
    value: str = ""


class Generation(SQLModel, table=True):
    """A video generated by the local model through ComfyUI."""
    id: int | None = Field(default=None, primary_key=True)
    prompt: str
    negative: str = ""
    image_path: str | None = None  # optional first frame
    # queued | running | done | failed | cancelled
    status: str = Field(default="queued", index=True)
    comfy_prompt_id: str | None = None
    queue_position: int | None = None
    video_path: str | None = None
    error: str | None = None
    created_at: datetime = Field(default_factory=utcnow)
    finished_at: datetime | None = None


class AssistantAction(SQLModel, table=True):
    """An action proposed by the assistant that waits for the user's confirmation."""
    id: int | None = Field(default=None, primary_key=True)
    kind: str  # start_generation | create_post
    args: str = "{}"  # JSON
    status: str = "pending"  # pending | done | cancelled | failed
    result: str = ""
    created_at: datetime = Field(default_factory=utcnow)

    @property
    def data(self) -> dict:
        return json.loads(self.args or "{}")


class AssistantMessage(SQLModel, table=True):
    """One message of the assistant chat (a single running conversation)."""
    id: int | None = Field(default=None, primary_key=True)
    role: str  # user | assistant | tool | event
    content: str = ""
    tool_calls: str = ""  # JSON list, for assistant messages that call tools
    tool_call_id: str = ""  # for tool results
    action_id: int | None = None  # an action card shown under this message
    created_at: datetime = Field(default_factory=utcnow)
