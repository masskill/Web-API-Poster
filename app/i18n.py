def translate(lang: str, key: str, **kwargs) -> str:
    pair = TEXTS.get(key)
    if pair is None:
        return key
    text = pair[LANGS.index(lang)] if lang in LANGS else pair[0]
    return text.format(**kwargs) if kwargs else text
